import os
import subprocess
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

base_url = os.environ.get('POS_TEST_BASE_URL', 'http://127.0.0.1:5174')
if not base_url.startswith('http://127.0.0.1:'):
    raise RuntimeError('Solo se permite el servidor local con emuladores.')

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path=os.environ['PLAYWRIGHT_CHROMIUM_EXECUTABLE'])
    context = browser.new_context(viewport={'width': 1365, 'height': 900})
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(base_url)
    page.wait_for_load_state('networkidle')
    assert page.evaluate("async () => (await import('/src/lib/firebase.ts')).firebaseConfig.projectId") == 'demo-denzoz-ops'
    page.locator('input[type=email]').fill('pos-ui@example.com')
    page.locator('input[type=password]').fill('UiTest123!')
    page.get_by_role('button', name='Ingresar al Sistema').click()
    page.wait_for_url('**/pos')
    field = page.get_by_role('combobox', name='Buscar productos')
    field.wait_for()
    field.fill('hojas bond')
    page.get_by_role('option').first.wait_for(timeout=30000)
    page.get_by_role('option').first.get_by_role('button').click()
    dialog = page.get_by_role('dialog', name='Hojas bond', exact=True)
    expect(dialog.get_by_role('button')).to_have_count(4)
    dialog.get_by_role('button', name='Unidad base', exact=False).click()
    expect(page.get_by_role('textbox', name='Cantidad de Hojas bond', exact=True)).to_have_value('1')
    expect(field).to_be_focused()
    page.get_by_role('textbox', name='Cantidad de Hojas bond', exact=True).fill('100')
    page.get_by_role('textbox', name='Cantidad de Hojas bond', exact=True).press('Enter')
    # Una sola presentación se agrega directamente, incluso fuera de las primeras tarjetas.
    field.fill('Producto 0305')
    field.press('Enter')
    expect(page.get_by_role('dialog')).to_have_count(0)
    expect(page.get_by_role('textbox', name='Cantidad de Producto 0305', exact=True)).to_have_value('1')
    # Escritura fuera del buscador captura desde el primer carácter.
    page.locator('h1').first.click() if page.locator('h1').count() else page.locator('body').click(position={'x': 5, 'y': 150})
    page.evaluate('document.activeElement.blur()')
    page.keyboard.type('hojs bond', delay=110)
    expect(field).to_have_value('hojs bond')
    page.get_by_role('option').first.get_by_role('button').click()
    expect(page.get_by_role('dialog', name='Hojas bond', exact=True)).to_be_visible()
    page.keyboard.press('Escape')
    expect(field).to_be_focused()
    # Una lectura rápida reemplaza un filtro anterior y selecciona su presentación exacta.
    field.fill('busqueda anterior')
    page.keyboard.type('BOND-MIL', delay=5)
    page.keyboard.press('Enter')
    millar = page.get_by_role('textbox', name='Cantidad de Hojas bond (MIL x1000)', exact=True)
    expect(millar).to_have_value('0.5')
    expect(page.get_by_role('dialog')).to_have_count(0)
    expect(field).to_have_value('')
    # Escribir rápido un nombre conserva todas las letras.
    page.keyboard.type('hojas bond', delay=5)
    page.keyboard.press('Enter')
    expect(page.get_by_role('dialog', name='Hojas bond', exact=True)).to_be_visible()
    page.keyboard.press('Escape')
    quantity = page.get_by_role('textbox', name='Cantidad de Hojas bond', exact=True)
    quantity.focus()
    quantity.fill('2')
    quantity.press('Enter')
    expect(field).to_have_value('')
    # Calendario compartido: creación, datos de formulario, finalización y permisos.
    page.goto(base_url + '/pos/calendario')
    for width in [320, 390, 768, 1024, 1280, 1600]:
        page.set_viewport_size({'width': width, 'height': 900})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
    page.set_viewport_size({'width': 1365, 'height': 900})
    page.get_by_role('button', name='Nuevo evento', exact=True).click()
    editor = page.get_by_role('dialog', name='Nuevo evento', exact=True)
    editor.get_by_label('Título *', exact=True).fill('Pagar alquiler UI')
    editor.get_by_label('Descripción', exact=True).fill('Compartido con admin y POS autorizado')
    editor.get_by_role('button', name='Guardar evento').click()
    expect(page.get_by_text('Evento guardado.', exact=True)).to_be_visible(timeout=30000)
    expect(page.get_by_role('heading', name='Pagar alquiler UI', exact=True)).to_be_visible()
    subprocess.run(['node', 'tools/dispatch-calendar-ui.mjs'], cwd=Path(__file__).resolve().parent.parent, env=os.environ.copy(), check=True, timeout=60)
    page.get_by_role('button', name='Recordatorios del calendario', exact=False).click()
    reminders = page.get_by_role('dialog', name='Recordatorios del calendario', exact=True)
    expect(reminders.get_by_text('Pagar alquiler UI', exact=True)).to_be_visible(timeout=30000)
    reminders.get_by_role('button', name='En 1 hora', exact=True).click()
    expect(reminders.get_by_text('Pospuesto', exact=False)).to_be_visible(timeout=30000)
    reminders.get_by_role('button', name='Marcar leído', exact=True).click()
    expect(reminders.get_by_role('button', name='Marcar leído', exact=True)).to_have_count(0, timeout=30000)
    reminders.get_by_role('button', name='Cerrar modal', exact=True).click()
    page.get_by_role('button', name='Activar notificaciones', exact=True).click()
    expect(page.get_by_text('Las notificaciones fuera del sistema aún no están habilitadas.', exact=False)).to_be_visible()
    mobile = browser.new_context(viewport={'width': 390, 'height': 844})
    admin_page = mobile.new_page()
    admin_page.on('pageerror', lambda error: errors.append(str(error)))
    admin_page.goto(base_url)
    admin_page.locator('input[type=email]').fill('admin-ui@example.com')
    admin_page.locator('input[type=password]').fill('UiTest123!')
    admin_page.get_by_role('button', name='Ingresar al Sistema').click()
    admin_page.wait_for_url('**/admin')
    admin_page.goto(base_url + '/admin/calendario')
    expect(admin_page.get_by_role('heading', name='Pagar alquiler UI', exact=True)).to_be_visible(timeout=30000)
    assert admin_page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    if os.environ.get('POS_SCREENSHOT_DIR'):
        images = Path(os.environ['POS_SCREENSHOT_DIR'])
        images.mkdir(parents=True, exist_ok=True)
        admin_page.screenshot(path=str(images / 'calendario-movil.png'), full_page=True)
        page.screenshot(path=str(images / 'calendario-pos.png'), full_page=True)
    admin_page.get_by_role('button', name='Completar', exact=True).click()
    expect(admin_page.get_by_text('Evento completado.', exact=True)).to_be_visible(timeout=30000)
    expect(page.get_by_role('heading', name='Pagar alquiler UI', exact=True)).to_have_count(0)
    # Revocación con la misma sesión abierta.
    admin_page.goto(base_url + '/admin/usuarios')
    row = admin_page.get_by_role('row').filter(has_text='pos-ui@example.com')
    row.get_by_role('button', name='Permitido', exact=True).click()
    expect(page.get_by_text('Tu cuenta no tiene acceso al calendario.', exact=False)).to_be_visible(timeout=30000)
    row.get_by_role('button', name='Sin acceso', exact=True).click()
    expect(page.get_by_role('button', name='Nuevo evento', exact=True)).to_be_visible(timeout=30000)
    assert not errors, errors
    print('POS/calendario verificado: selector, teclado, lector, búsqueda, formularios, permisos en vivo y vista móvil.')
    browser.close()
