import os
import re
from playwright.sync_api import sync_playwright, expect

base_url = os.environ.get('POS_TEST_BASE_URL', 'http://127.0.0.1:5174')
if not base_url.startswith('http://127.0.0.1:'):
    raise RuntimeError('Esta prueba solo permite el servidor local con emuladores.')

with sync_playwright() as playwright:
    executable = os.environ.get('PLAYWRIGHT_CHROMIUM_EXECUTABLE')
    browser = playwright.chromium.launch(headless=True, **({'executable_path': executable} if executable else {}))
    page = browser.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(base_url)
    page.wait_for_load_state('networkidle')
    project = page.evaluate("async () => (await import('/src/lib/firebase.ts')).firebaseConfig.projectId")
    assert project == 'demo-denzoz-ops', project
    page.evaluate("localStorage.setItem('denzoz_pos_cart_tenant-ui_S1', JSON.stringify({clientDoc:{tipo:'DNI',numero:'12345678',nombre:'Privado'}}))")
    page.locator('input[type=email]').fill('pos-ui@example.com')
    page.locator('input[type=password]').fill('UiTest123!')
    page.get_by_role('button', name='Ingresar al Sistema').click()
    page.wait_for_url(lambda url: url.endswith('/pos'))
    page.get_by_placeholder('Busca por nombre', exact=False).wait_for()
    assert page.evaluate("localStorage.getItem('denzoz_pos_cart_tenant-ui_S1')") is None
    page.goto(base_url + '/pos/caja')
    page.get_by_role('button', name='Abrir caja e iniciar turno').click()
    page.get_by_text('Turno activo (caja abierta)', exact=False).wait_for(timeout=30000)
    page.goto(base_url + '/pos')
    page.get_by_placeholder('Busca por nombre', exact=False).fill('0305')
    product = page.get_by_role('button', name=re.compile(r'Producto 0305 \(UN\)'))
    product.wait_for(timeout=30000)
    expect(product).to_contain_text('7.00')
    expect(product).to_contain_text('10 en stock')
    product.click()
    charge = page.get_by_role('button', name='Cobrar S/ 7.00', exact=True)
    charge.wait_for()
    page.get_by_role('button', name='Nota de Venta', exact=True).click()
    page.get_by_placeholder('7.00', exact=True).fill('10')
    expect(charge).to_be_enabled()
    drafts = page.evaluate("Object.keys(localStorage).filter(k=>k.startsWith('denzoz_pos_cart_v2_')).map(k=>JSON.parse(localStorage.getItem(k)))")
    assert drafts and all('clientDoc' not in draft for draft in drafts)

    def lose_response(route):
        response = route.fetch()
        assert response.ok, response.text()
        route.abort()

    page.route('**/createSaleRecord', lose_response)
    charge.click()
    page.get_by_text('Cobro pendiente de confirmar', exact=True).wait_for(timeout=30000)
    page.reload()
    page.get_by_role('button', name='Verificar y recuperar cobro', exact=True).wait_for(timeout=30000)
    page.get_by_role('button', name='Verificar y recuperar cobro', exact=True).click()
    page.get_by_text('Venta Emitida con Éxito', exact=True).wait_for(timeout=30000)
    assert not page.evaluate("Object.keys(localStorage).some(k=>k.startsWith('denzoz_pending_sale_v1_'))")
    page.get_by_role('button', name='Nueva Venta', exact=True).click()
    page.get_by_placeholder('Busca por nombre', exact=False).fill('BOND-UN')
    page.get_by_placeholder('Busca por nombre', exact=False).press('Enter')
    base_quantity = page.get_by_role('textbox', name='Cantidad de Hojas bond', exact=True)
    base_quantity.fill('100')
    base_quantity.press('Enter')
    page.get_by_role('button', name='Nota de Venta', exact=True).click()
    page.get_by_placeholder('20.00', exact=True).fill('20')
    page.unroute('**/createSaleRecord', lose_response)
    page.get_by_role('button', name='Cobrar S/ 20.00', exact=True).click()
    page.get_by_text('Venta Emitida con Éxito', exact=True).wait_for(timeout=30000)
    page.get_by_role('button', name='Nueva Venta', exact=True).click()
    page.get_by_placeholder('Busca por nombre', exact=False).fill('BOND-MIL')
    millar = page.get_by_role('button', name=re.compile(r'Hojas bond \(MIL x1000\)'))
    expect(millar).to_contain_text('0.95 en stock', timeout=30000)
    page.get_by_placeholder('Busca por nombre', exact=False).press('Enter')
    half_quantity = page.get_by_role('textbox', name='Cantidad de Hojas bond (MIL x1000)', exact=True)
    expect(half_quantity).to_have_value('0.5')
    half_quantity.fill('1')
    half_quantity.press('Enter')
    expect(half_quantity).to_have_value('0.5')
    page.get_by_text('Stock total insuficiente de Hojas bond', exact=False).wait_for()
    half_quantity.fill('0,5')
    half_quantity.press('Enter')
    page.get_by_role('button', name='Nota de Venta', exact=True).click()
    page.get_by_role('button', name='Yape', exact=True).click()
    page.get_by_role('button', name='Cobrar S/ 50.00', exact=True).click()
    page.get_by_text('Venta Emitida con Éxito', exact=True).wait_for(timeout=30000)
    page.get_by_role('button', name='Nueva Venta', exact=True).click()
    page.get_by_placeholder('Busca por nombre', exact=False).fill('BOND-UN')
    expect(page.get_by_role('button', name=re.compile(r'Hojas bond \(UN\)'))).to_contain_text('450 en stock', timeout=30000)
    worker_page = browser.new_page()
    worker_page.on('pageerror', lambda error: errors.append(str(error)))
    worker_page.goto(base_url)
    worker_page.locator('input[type=email]').fill('worker-ui@example.com')
    worker_page.locator('input[type=password]').fill('UiTest123!')
    worker_page.get_by_role('button', name='Ingresar al Sistema').click()
    worker_page.wait_for_url(lambda url: url.endswith('/w'))
    worker_page.get_by_placeholder('Escribe el nombre o escanea código', exact=False).fill('BOND-MIL')
    worker_page.get_by_placeholder('Escribe el nombre o escanea código', exact=False).press('Enter')
    expect(worker_page.get_by_text('Equivalente disponible:', exact=False).filter(has_text='Millar')).to_contain_text('0.45 Millar', timeout=30000)
    worker_page.goto(base_url + '/w/cotizaciones')
    worker_page.get_by_placeholder('Escribe el nombre o escanea código', exact=False).fill('BOND-CTO')
    worker_page.get_by_role('button', name=re.compile(r'Hojas bond \(CTO x100\)')).click()
    worker_page.locator('input[type=number]').fill('0.5')
    worker_page.get_by_role('button', name='Guardar Cotización en el Sistema', exact=True).click()
    worker_page.get_by_text('no permite venta fraccionada', exact=False).wait_for()
    worker_page.locator('input[type=number]').fill('2')
    worker_page.get_by_role('button', name='Guardar Cotización en el Sistema', exact=True).click()
    worker_page.get_by_text('guardada exitosamente', exact=False).wait_for(timeout=30000)
    worker_page.close()
    assert not errors, errors
    print('POS verificado: precio vigente, privacidad, recuperación de cobro y 1050 -> 950 -> 450 hojas usando 0.5 millar a S/50.')
    browser.close()
